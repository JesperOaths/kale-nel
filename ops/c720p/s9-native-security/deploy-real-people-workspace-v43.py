def put(path,data,old_stat):
 fd,temp=tempfile.mkstemp(prefix=".pfv43-",dir=path.parent)
 try:
  with os.fdopen(fd,"wb") as f:
   f.write(data);f.flush();os.fsync(f.fileno())
  os.chmod(temp,stat.S_IMODE(old_stat.st_mode))
  try:os.chown(temp,old_stat.st_uid,old_stat.st_gid)
  except PermissionError:pass
  os.replace(temp,path)
 finally:
  if os.path.exists(temp):os.unlink(temp)

def get(url,max_bytes=100000):
 with urllib.request.urlopen(url,timeout=20) as r:
  if r.status!=200:raise RuntimeError("readback_status")
  data=r.read(max_bytes+1)
 if len(data)>max_bytes or len(data)<100:raise RuntimeError("readback_size")
 return data

def archive_names():
 blob=get("http://127.0.0.1:8795/new/api/saved",1500000)
 data=json.loads(blob)
 if data.get("archive_mode")!="S9-microSD-only":raise RuntimeError("archive_mode_changed")
 names={x.get("clip_no") for x in data.get("events",[]) if isinstance(x,dict)}
 if len(names)<50:raise RuntimeError("original_archive_unavailable")
 return names


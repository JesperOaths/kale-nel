create or replace function c720p_agent.submit_management_job_v1(
 p_actor text, p_operation text, p_command text,
 p_timeout_seconds integer, p_idempotency_key text
)
returns table(job_id bigint, job_state text, disposition text)
language plpgsql security invoker set search_path = pg_catalog
as $fn$
declare
 v_id bigint;
 v_state text;
 v_new boolean := false;
begin
 if session_user <> 'postgres' or current_user <> 'postgres' then
   raise exception 'management_role_required' using errcode='42501';
 end if;
 if p_actor is null or p_actor !~ '^[a-zA-Z0-9_.:@-]{3,100}$' then
   raise exception 'invalid_actor' using errcode='22023';
 end if;
 if p_operation not in
   ('diagnostic','maintenance','deployment','adb','ssh','home_automation','security') then
   raise exception 'invalid_operation' using errcode='22023';
 end if;
 if p_command is null or length(p_command) < 3 or length(p_command) > 16000 then
   raise exception 'invalid_command_size' using errcode='22023';
 end if;
 if p_timeout_seconds is null or p_timeout_seconds < 5 or p_timeout_seconds > 900 then
   raise exception 'invalid_timeout' using errcode='22023';
 end if;
 if p_idempotency_key is null or p_idempotency_key !~ '^[A-Za-z0-9._:-]{12,128}$' then
   raise exception 'invalid_idempotency_key' using errcode='22023';
 end if;
 insert into c720p_agent.jobs(command,timeout_seconds,idempotency_key)
 values (p_command,p_timeout_seconds,p_idempotency_key)
 on conflict (idempotency_key) do nothing
 returning id,state into v_id,v_state;
 if v_id is not null then
   v_new := true;
 else
   select j.id,j.state into v_id,v_state
   from c720p_agent.jobs j where j.idempotency_key=p_idempotency_key;
   if v_id is null then
     raise exception 'idempotency_conflict' using errcode='23505';
   end if;
   if not exists (
     select 1 from c720p_agent.jobs j where j.id=v_id and j.command=p_command
   ) then
     raise exception 'idempotency_command_mismatch' using errcode='23505';
   end if;
 end if;
 insert into c720p_agent.command_gateway_audit_v1
   (job_id,actor,operation,source,command_sha256,idempotency_key,disposition)
 values (
   v_id,p_actor,p_operation,'supabase_management',
   encode(sha256(convert_to(p_command,'UTF8')),'hex'),
   p_idempotency_key,
   case when v_new then 'queued' else 'idempotent_replay' end
 );
 return query select v_id,v_state,
   case when v_new then 'queued'::text else 'idempotent_replay'::text end;
end
$fn$;
revoke all on function

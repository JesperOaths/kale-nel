#!/usr/bin/env python3
"""Read-only monotonic HTTPS Date time witness for future signed S9 intents.

Not an NTP repair or token issuer. CA-verified HTTPS, exact allowlisted host,
uncached response, low latency, agreement of >=2 independent domains and
single-digit-second age must all hold BEFORE an action relay could consider
this UTC witness. Never broadens V198's expiry/clock-skew/HMAC conditions.
No real keys or signed actions are generated by this module.
"""
import dataclasses
import email.utils
import json
import statistics
import time
import urllib.parse
import urllib.request

SOURCES=("www.cloudflare.com","www.google.com","www.microsoft.com")
TIMEOUT_SECONDS=4
MAX_RTT_SECONDS=1.5
MIN_DISTINCT_SOURCES=2
MAX_SPREAD_SECONDS=2.5
MAX_WITNESS_AGE_SECONDS=5.0
MARK="S9_SIGNED_TIME_WITNESS_V234 "

class Refusal(Exception):pass
def need(ok,reason):
 if not ok:raise Refusal(reason)

@dataclasses.dataclass(frozen=True)
class Sample:
 host:str
 server_seconds:float
 midpoint_monotonic:float
 rtt_seconds:float

@dataclasses.dataclass(frozen=True)
class Witness:
 baseline_server_seconds:float
 baseline_monotonic:float
 source_count:int
 spread_seconds:float
 def epoch_millis(self,now_monotonic):
  age=now_monotonic-self.baseline_monotonic
  need(0<=age<=MAX_WITNESS_AGE_SECONDS,"trusted_time_witness_expired")
  return int((self.baseline_server_seconds+age)*1000)

def probe(host):
 need(host in SOURCES,"time_origin_not_allowlisted")
 req=urllib.request.Request("https://"+host+"/",method="HEAD",
     headers={"User-Agent":"s9-time-witness-v234",
              "Cache-Control":"no-cache, no-store","Pragma":"no-cache"})
 start=time.monotonic()
 try:
  with urllib.request.urlopen(req,timeout=TIMEOUT_SECONDS) as response:
   finish=time.monotonic()
   need(response.status in (200,204),"https_date_status_untrusted")
   uri=urllib.parse.urlparse(response.geturl())
   need(uri.scheme=="https" and uri.hostname==host and uri.port is None
        and uri.username is None and uri.password is None,
        "https_date_cross_origin_redirect")
   raw=response.headers.get("Date")
   age=response.headers.get("Age")
   need(age is None or age.strip()=="0","cached_https_date_rejected")
 except (OSError,ValueError):
  raise Refusal("https_date_probe_unavailable") from None
 rtt=finish-start
 need(0<=rtt<=MAX_RTT_SECONDS,"https_date_response_too_slow")
 try:
  date=email.utils.parsedate_to_datetime(raw)
  need(date.tzinfo is not None and date.utcoffset().total_seconds()==0,
       "https_date_not_utc")
  epoch=date.timestamp()
 except (AttributeError,TypeError,ValueError,OverflowError):
  raise Refusal("https_date_invalid") from None
 need(1700000000<=epoch<=2147483647,"https_date_outside_supported_range")
 # Date header truncates to whole seconds. Center its rounding uncertainty.
 return Sample(host,float(epoch)+0.5,(start+finish)/2,rtt)

def establish(samples,now_monotonic):
 need(type(now_monotonic) in (int,float) and 0<now_monotonic<1e13,
      "monotonic_clock_invalid")
 valid=[]
 seen=set()
 for entry in samples:
  need(isinstance(entry,Sample) and entry.host in SOURCES
       and entry.host not in seen and type(entry.server_seconds) in (int,float)
       and 1700000000<=entry.server_seconds<=2147483648
       and type(entry.midpoint_monotonic) in (int,float)
       and type(entry.rtt_seconds) in (int,float)
       and 0<=entry.rtt_seconds<=MAX_RTT_SECONDS,
       "time_sample_untrusted")
  age=now_monotonic-entry.midpoint_monotonic
  need(0<=age<=MAX_WITNESS_AGE_SECONDS,
       "time_sample_expired_or_monotonic_reversed")
  valid.append(entry.server_seconds+age)
  seen.add(entry.host)
 need(len(seen)>=MIN_DISTINCT_SOURCES,"insufficient_independent_https_times")
 spread=max(valid)-min(valid)
 need(spread<=MAX_SPREAD_SECONDS,"independent_https_times_disagree")
 return Witness(statistics.median(valid),now_monotonic,len(seen),spread)

def camera():
 try:
  with urllib.request.urlopen("http://127.0.0.1:18808/status",timeout=5) as r:
   need(r.status==200,"native_camera_unreachable")
   data=r.read(65537)
  need(len(data)<=65536,"native_camera_status_unbounded")
  obj=json.loads(data)
 except (OSError,ValueError,TypeError):
  raise Refusal("native_camera_unreachable") from None
 need(obj.get("ok") is True and obj.get("mode")=="watching"
      and obj.get("native_4k_enabled") is True
      and obj.get("continuous_4k_ready") is True
      and obj.get("continuous_4k_dropped_output_frames")==0
      and not obj.get("continuous_4k_error")
      and type(obj.get("temperature_c")) in (int,float)
      and 0<obj["temperature_c"]<=39.5,
      "native_4k_not_healthy")
 return {"ready":True,"output_drops":0,"temperature_c":obj["temperature_c"]}

def audit():
 before=camera()
 # Any failed or slow source is excluded, never counted as positive agreement.
 samples=[]
 exclusions=0
 for host in SOURCES:
  try:samples.append(probe(host))
  except Refusal:exclusions+=1
 now=time.monotonic()
 witness=establish(samples,now)
 observed_wall=time.time()
 estimated=witness.epoch_millis(now)/1000
 after=camera()
 return {"status":"independent_tls_witness_verified",
   "measured_sources":witness.source_count,
   "excluded_sources":exclusions,
   "source_spread_s":round(witness.spread_seconds,2),
   "remote_minus_hub_wall_s":round(estimated-observed_wall,2),
   "hub_clock_repaired":False,
   "ntp_enabled_or_changed_by_audit":False,
   "future_production_signing_enabled":False,
   "not_an_authenticated_action":True,
   "not_an_s9_clock_attestation":True,
   "witness_max_age_s":MAX_WITNESS_AGE_SECONDS,
   "bypasses_v198_signature_or_expiry":False,
   "camera_ready_before_after":before["ready"] and after["ready"],
   "camera_temperature_after_c":after["temperature_c"],
   "camera_dropped_frames_after":after["output_drops"],
   "real_video_or_review_access":False,
   "private_secrets_accessed":False,
   "read_only":True}

def main():
 try:result=audit()
 except Exception as exc:
  reason=str(exc) if isinstance(exc,Refusal) else "unexpected_witness_error"
  allowed={
   "monotonic_clock_invalid","time_sample_untrusted",
   "time_sample_expired_or_monotonic_reversed",
   "insufficient_independent_https_times",
   "independent_https_times_disagree","native_camera_unreachable",
   "native_camera_status_unbounded","native_4k_not_healthy"}
  result={"status":"inconclusive","reason":reason if reason in allowed
          else "witness_unavailable","future_production_signing_enabled":False,
          "hub_clock_repaired":False,"real_video_or_review_access":False,
          "private_secrets_accessed":False,"read_only":True}
 print(MARK+json.dumps(result,sort_keys=True,separators=(",",":")),flush=True)
 if result["status"]=="inconclusive":raise SystemExit(1)

if __name__=="__main__":main()

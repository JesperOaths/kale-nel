create or replace function public.shop_apply_payment_fee_v847(order_id_input uuid, admin_id_input bigint default null)
returns jsonb language plpgsql security definer set search_path='public'
as $function$
declare o public.shop_orders%rowtype; r public.shop_payment_fee_rules_v847%rowtype; base_cents integer; fee_cents integer; ledger_id bigint;
begin
  select * into o from public.shop_orders where id=order_id_input;
  if not found then return jsonb_build_object('ok',false,'error','order_not_found'); end if;
  select * into r from public.shop_payment_fee_rules_v847 where provider=coalesce(o.payment_provider,'manual_transfer') and enabled=true limit 1;
  if not found then return jsonb_build_object('ok',true,'configured',false,'payment_fee_cents',o.payment_fee_cents); end if;
  base_cents:=coalesce(o.paid_amount_cents,o.total_cents,0);
  fee_cents:=greatest(0,round(base_cents*r.rate_bps::numeric/10000)::integer+r.fixed_fee_cents);
  update public.shop_orders set payment_fee_cents=fee_cents,payment_fee_source='configured_rule',payment_fee_rule_id=r.id,updated_at=now() where id=o.id;
  select id into ledger_id from public.shop_finance_ledger_v841 where order_id=o.id and direction='cost' and category='payment_fee' order by id desc limit 1;
  if ledger_id is null and fee_cents>0 then
    insert into public.shop_finance_ledger_v841(occurred_on,direction,category,amount_cents,currency,order_id,note,created_by_admin_id,updated_at)
    values((coalesce(o.payment_verified_at,o.paid_at,now()) at time zone 'Europe/Amsterdam')::date,'cost','payment_fee',fee_cents,'eur',o.id,'Automatically calculated from configured payment-provider fee rule.',admin_id_input,now())
    returning id into ledger_id;
  end if;
  return jsonb_build_object('ok',true,'configured',true,'provider',r.provider,'payment_fee_cents',fee_cents,'ledger_id',ledger_id,'rule_id',r.id);
end;$function$;

create or replace function public.shop_issue_invoice_v847(order_id_input uuid)
returns jsonb language plpgsql security definer set search_path='public'
as $function$
declare o public.shop_orders%rowtype; s public.shop_tax_invoice_settings_v847%rowtype; existing public.shop_invoices_v847%rowtype; seq_no bigint; invoice_no text; vat_cents integer; net_cents integer; status text:='unconfigured'; new_id bigint;
begin
  select * into existing from public.shop_invoices_v847 where order_id=order_id_input;
  if found then return jsonb_build_object('ok',true,'existing',true,'invoice_number',existing.invoice_number,'invoice_id',existing.id,'tax_status',existing.tax_status); end if;
  select * into o from public.shop_orders where id=order_id_input;
  if not found then return jsonb_build_object('ok',false,'error','order_not_found'); end if;
  if o.payment_verified_at is null then return jsonb_build_object('ok',false,'error','payment_not_verified'); end if;
  select * into s from public.shop_tax_invoice_settings_v847 where id=1;
  if not found or s.invoicing_enabled is not true then return jsonb_build_object('ok',true,'skipped',true,'reason','invoicing_disabled'); end if;
  if s.tax_calculation_enabled and s.default_vat_rate_bps is not null then
    vat_cents:=round(coalesce(o.total_cents,0)*s.default_vat_rate_bps::numeric/(10000+s.default_vat_rate_bps))::integer;
    net_cents:=coalesce(o.total_cents,0)-vat_cents; status:='configured';
  else vat_cents:=null; net_cents:=null; status:='unconfigured'; end if;
  seq_no:=nextval('public.shop_invoice_number_v847_seq');
  invoice_no:=regexp_replace(coalesce(s.invoice_prefix,'BRUIS'),'[^A-Za-z0-9_-]','','g')||'-'||to_char(now() at time zone 'Europe/Amsterdam','YYYY')||'-'||lpad(seq_no::text,6,'0');
  insert into public.shop_invoices_v847(invoice_number,order_id,issued_at,currency,gross_total_cents,net_total_cents,vat_total_cents,vat_rate_bps,tax_status,customer,line_items,seller,note)
  values(invoice_no,o.id,now(),coalesce(o.currency,'eur'),coalesce(o.total_cents,0),net_cents,vat_cents,case when status='configured' then s.default_vat_rate_bps else null end,status,
    jsonb_build_object('name',o.customer_name,'email',o.customer_email,'phone',o.customer_phone,'shipping_address',o.shipping_address),
    coalesce(o.line_items,'[]'::jsonb),
    jsonb_build_object('name',s.seller_name,'address',s.seller_address,'postal_city',s.seller_postal_city,'country',s.seller_country,'vat_number',s.vat_number,'kvk_number',s.kvk_number),
    s.invoice_note) returning id into new_id;
  update public.shop_orders set invoice_number=invoice_no,updated_at=now() where id=o.id;
  return jsonb_build_object('ok',true,'existing',false,'invoice_number',invoice_no,'invoice_id',new_id,'tax_status',status);
end;$function$;


create or replace function public.admin_list_security_v847(admin_session_token_input text)
returns jsonb language plpgsql security definer set search_path='public'
as $function$
declare sess record; current_hash text; current_id bigint; sessions_json jsonb; devices_json jsonb;
begin
  select * into sess from public._require_valid_admin_session(admin_session_token_input);
  if coalesce(sess.ok,false) is not true then return jsonb_build_object('ok',false,'error','invalid_admin_session'); end if;
  current_hash:=public._hash_session_token(admin_session_token_input);
  select id into current_id from public.admin_sessions where token_hash=current_hash and expires_at>now() limit 1;
  select coalesce(jsonb_agg(jsonb_build_object('id',s.id,'created_at',s.created_at,'last_used_at',s.last_used_at,'expires_at',s.expires_at,'is_current',(s.id=current_id)) order by s.last_used_at desc nulls last),'[]'::jsonb)
  into sessions_json from public.admin_sessions s where s.admin_id=sess.admin_id and s.expires_at>now();
  select coalesce(jsonb_agg(jsonb_build_object('id',d.id,'device_label',d.device_label,'trusted_at',d.trusted_at,'last_seen_at',d.last_seen_at,'expires_at',d.expires_at,'revoked_at',d.revoked_at,'active',(d.revoked_at is null and d.expires_at>now())) order by d.last_seen_at desc nulls last),'[]'::jsonb)
  into devices_json from public.admin_trusted_devices d where lower(d.admin_username)=lower(sess.username);
  return jsonb_build_object('ok',true,'admin_username',sess.username,'current_session_id',current_id,'sessions',sessions_json,'devices',devices_json);
end;$function$;

create or replace function public.admin_revoke_trusted_device_v847(admin_session_token_input text,device_id_input bigint)

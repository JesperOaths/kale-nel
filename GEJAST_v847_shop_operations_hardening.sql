end;$function$;

create or replace function public.admin_revoke_session_v847(admin_session_token_input text,session_id_input bigint)
returns jsonb language plpgsql security definer set search_path='public'
as $function$
declare sess record; current_hash text; current_id bigint;
begin
  select * into sess from public._require_valid_admin_session(admin_session_token_input);
  if coalesce(sess.ok,false) is not true then return jsonb_build_object('ok',false,'error','invalid_admin_session'); end if;
  current_hash:=public._hash_session_token(admin_session_token_input);
  select id into current_id from public.admin_sessions where token_hash=current_hash and expires_at>now() limit 1;
  if session_id_input=current_id then return jsonb_build_object('ok',false,'error','cannot_revoke_current_session_here'); end if;
  delete from public.admin_sessions where id=session_id_input and admin_id=sess.admin_id;
  return jsonb_build_object('ok',true);
end;$function$;

create or replace function public.admin_revoke_other_sessions_v847(admin_session_token_input text)
returns jsonb language plpgsql security definer set search_path='public'
as $function$
declare sess record; current_hash text; deleted_count integer;
begin
  select * into sess from public._require_valid_admin_session(admin_session_token_input);
  if coalesce(sess.ok,false) is not true then return jsonb_build_object('ok',false,'error','invalid_admin_session'); end if;
  current_hash:=public._hash_session_token(admin_session_token_input);
  delete from public.admin_sessions where admin_id=sess.admin_id and token_hash<>current_hash;
  get diagnostics deleted_count=row_count;
  return jsonb_build_object('ok',true,'revoked_sessions',deleted_count);
end;$function$;


comment on table public.shop_product_cost_cache_v841 is 'Private admin-only current catalog production-cost snapshot for shop analytics v841.';
comment on function public.shop_admin_analytics_snapshot_v841(timestamptz,timestamptz) is 'Service-role-only aggregated shop analytics snapshot for protected v841 admin API.';
commit;

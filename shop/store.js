function initializeGalleries(){
  qsa('.product-card').forEach(card => {
    const rail = card.querySelector('.mockup-rail');
    const slides = qsa.call ? [...card.querySelectorAll('.mockup')] : Array.from(card.querySelectorAll('.mockup'));
    const dots = Array.from(card.querySelectorAll('[data-gallery-dot]'));
    if(!rail || !slides.length || !dots.length) return;
    const setActive = index => dots.forEach((dot, i) => dot.classList.toggle('active', i === index));
    const currentIndex = () => Math.max(0, Math.min(slides.length - 1, Math.round(rail.scrollLeft / Math.max(1, rail.clientWidth * 0.82))));
    const goTo = index => {
      const next = (index + slides.length) % slides.length;
      rail.scrollTo({ left: slides[next].offsetLeft - rail.offsetLeft - 18, behavior:'smooth' });
      setActive(next);
    };
    dots.forEach((dot, index) => dot.addEventListener('click', () => goTo(index)));
    card.querySelector('[data-gallery-prev]')?.addEventListener('click', () => goTo(currentIndex() - 1));
    card.querySelector('[data-gallery-next]')?.addEventListener('click', () => goTo(currentIndex() + 1));
    rail.addEventListener('scroll', () => {
      window.requestAnimationFrame(() => setActive(currentIndex()));
    }, { passive:true });
  });
}

function saveCart(){ localStorage.setItem(cartKey, JSON.stringify(cart)); }
function cartTotal(){ return cart.reduce((sum,item) => sum + item.price * item.qty, 0); }
function cartCount(){ return cart.reduce((sum,item) => sum + item.qty, 0); }

function renderCart(){
  qsa('[data-cart-count]').forEach(el => el.textContent = cartCount());
  qs('[data-cart-subtotal]').textContent = money(cartTotal());
  const items = qs('[data-cart-items]');
  if(!cart.length){
    items.innerHTML = '<p class="empty-cart">Your cart is empty. Add a shirt from the collection.</p>';
  } else {
    items.innerHTML = cart.map((item, index) => `
      <article class="cart-line">
        <img src="${esc(item.image)}" alt="${esc(item.name)}" />
        <div>
          <strong>${esc(item.name)}</strong>
          <span>${esc(item.size)} · ${item.qty} × ${money(item.price)}</span>
          <button type="button" data-remove="${index}">Remove</button>
        </div>
      </article>`).join('');
  }
  const summary = cart.map(i => `${i.qty}× ${i.name} (${i.size})`).join('\n') || 'I would like to order Bruis shirts.';
  qs('[data-mail-order]').href = `mailto:hello@example.com?subject=Bruis%20order%20request&body=${encodeURIComponent(summary)}`;
}

function addToCart(id){
  const product = products.find(p => p.id === id);
  if(!product) return;
  const size = qs(`[data-size="${id}"]`).value;
  const qty = Math.max(1, Math.min(9, Number(qs(`[data-qty="${id}"]`).value || 1)));
  const existing = cart.find(item => item.id === id && item.size === size);
  if(existing) existing.qty += qty;
  else cart.push({ id, size, qty, name:product.name, price:product.price, image:product.image });
  saveCart(); renderCart(); openCart();
}

function openCart(){ qs('[data-cart-drawer]').classList.add('open'); qs('[data-cart-drawer]').setAttribute('aria-hidden','false'); }
function closeCart(){ qs('[data-cart-drawer]').classList.remove('open'); qs('[data-cart-drawer]').setAttribute('aria-hidden','true'); }

async function init(){
  products = await loadCatalog();
  renderProducts(); renderCart();
  const count = qs('[data-product-count]');
  if(count) count.textContent = products.length;
}

init();

document.addEventListener('click', event => {
  const add = event.target.closest('[data-add]');
  if(add) addToCart(add.dataset.add);
  if(event.target.closest('[data-open-cart]')) openCart();
  if(event.target.closest('[data-close-cart]') || event.target === qs('[data-cart-drawer]')) closeCart();
  const remove = event.target.closest('[data-remove]');
  if(remove){ cart.splice(Number(remove.dataset.remove), 1); saveCart(); renderCart(); }
  const pill = event.target.closest('[data-filter]');
  if(pill){ filter = pill.dataset.filter; qsa('[data-filter]').forEach(p => p.classList.toggle('active', p === pill)); renderProducts(); }
});

